// Copies the compiled bytecode into functions/_lib/chain-contracts.js, which the admin page's deploy button sends.
// node scripts/export.mjs          write it (after `npx hardhat compile`)
// node scripts/export.mjs --check  fail if the committed file does not match the contracts (CI)
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const here = new URL('../', import.meta.url).pathname, out = new URL('../../functions/_lib/chain-contracts.js', import.meta.url).pathname;
const artifact = name => JSON.parse(readFileSync(`${here}artifacts/contracts/${name}.sol/${name}.json`, 'utf8'));
const source = name => createHash('sha256').update(readFileSync(`${here}contracts/${name}.sol`)).digest('hex').slice(0, 16);
const entry = name => `{name: '${name}', sources: '${source(name)}',\n  bytecode: '${artifact(name).bytecode}'}`;
const text = `// GENERATED by contracts/scripts/export.mjs from contracts/contracts/*.sol (solc 0.8.28 via npm, optimizer 200 runs).
// Do not edit: change the .sol file, run \`npm run build\` in contracts/, commit both. CI checks they match.
export const TOKEN = ${entry('RescueTestToken')};
export const HEROES = ${entry('RescueTestHeroes')};
`;
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch {}
  if (current !== text) { console.error('functions/_lib/chain-contracts.js is out of date: run `npm run build` in contracts/'); process.exit(1); }
  console.log('chain-contracts.js matches the contracts');
} else { writeFileSync(out, text); console.log('wrote', out); }
